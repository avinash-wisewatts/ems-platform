/**
 * Reports -> Create report (ADR-025): the weekly and monthly PDF reports of
 * the site selected in the application sidebar (no site selector here,
 * ADR-025 Amendment 1, A117). Every profile views and downloads (A5).
 *
 * Shows the combined history (Weekly / Monthly filter, status filter), each
 * report's reporting and comparison periods, generation time, status
 * (Pending, Processing, Generated, Failed) with the "Incomplete data" label
 * and the separate "Comparison incomplete" indicator (A109), a coverage
 * summary, version details (data coverage and settings used, A58) and PDF
 * download.
 *
 * On-demand generation (A113): Site Admins and WiseWatts Admins
 * (can_generate from the API; the database re-checks) choose a type and an
 * ENDED period and request it -- a new report, or a new version of an
 * existing one (earlier versions stay). Historical periods are generated only
 * when explicitly requested here (A115). Operators and Viewers see no
 * Generate control. Retry, delete, restore and all reporting configuration
 * stay WiseWatts Admin actions in the Administration App.
 *
 * A report whose settings came from a PO-approved retrospective reporting
 * baseline is labelled "Retrospective baseline" (A116).
 *
 * All times are shown in the site's timezone.
 */
