/**
 * Reports -> Create report (ADR-025): the weekly and monthly PDF reports of
 * the selected site, READ-ONLY for every profile (A5, A107).
 *
 * Shows the combined history (Weekly / Monthly filter, status filter), each
 * report's reporting and comparison periods, generation time, status
 * (Pending, Processing, Generated, Failed) with the "Incomplete data" label
 * and the separate "Comparison incomplete" indicator (A109), a coverage
 * summary, version details (data coverage and settings used, A58) and PDF
 * download. Generating, regenerating, retrying, deleting and restoring
 * reports -- and all reporting configuration -- are done by WiseWatts
 * Admins in the Administration App; nothing here changes a report.
 *
 * All times are shown in the site's timezone.
 */
import { useCallback, useEffect, useMemo, useState } from "react";
import { downloadSiteReportVersion, getSiteReportVersions, getSiteReports } from "../../../api/endpoints";
import type {
  SiteReportItem,
  SiteReportListResponse,
  SiteReportStatus,
  SiteReportType,
  SiteReportVersion,
} from "../../../api/types";
import { EmptyState } from "../../../components/states/EmptyState";
import { downloadBlob } from "../../../export/downloadCsv";
import { useTenant } from "../../../tenant/TenantProvider";

export const CREATE_REPORT_MESSAGES = {
  notEnrolled: "Weekly and monthly reports are not set up for this site.",
  empty: "No reports yet. Reports appear here after each week or month ends.",
  loadFailed: "Unable to load reports. Please try again.",
  downloadFailed: "The report could not be downloaded. Please try again.",
  readOnly: "Reports are generated by WiseWatts. You can view and download them here.",
} as const;

const POLL_MS = 10_000;
const STATUS_TONE: Record<SiteReportStatus, string> = {
  PENDING: "neutral",
  PROCESSING: "info",
  GENERATED: "good",
  FAILED: "bad",
};
const STATUS_LABEL: Record<SiteReportStatus, string> = {
  PENDING: "Pending",
  PROCESSING: "Processing",
  GENERATED: "Generated",
  FAILED: "Failed",
};

function formatDate(isoDate: string): string {
  const [y, m, d] = isoDate.split("-").map(Number);
  return new Date(Date.UTC(y!, m! - 1, d!)).toLocaleDateString("en-GB", {
    day: "2-digit",
    month: "short",
    year: "numeric",
    timeZone: "UTC",
  });
}

function formatInstant(iso: string | null, timeZone: string): string {
  if (!iso) return "—";
  return new Date(iso).toLocaleString("en-GB", {
    day: "2-digit",
    month: "short",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
    hour12: false,
    timeZone,
  });
}

function periodText(report: SiteReportItem, comparison = false): string {
  const start = comparison ? report.comparison_start : report.period_start;
  const end = comparison ? report.comparison_end : report.period_end;
  if (report.report_type === "MONTHLY") {
    const [y, m] = start.split("-").map(Number);
    return new Date(Date.UTC(y!, m! - 1, 1)).toLocaleDateString("en-GB", { month: "long", year: "numeric", timeZone: "UTC" });
  }
  return `${formatDate(start)} – ${formatDate(end)}`;
}

function pct(value: unknown): string {
  return typeof value === "number" ? `${value.toFixed(1)} %` : "—";
}

async function saveVersion(versionId: string, fallbackName: string): Promise<void> {
  const { blob, fileName } = await downloadSiteReportVersion(versionId);
  downloadBlob(fileName ?? fallbackName, blob);
}

export function CreateReportTab() {
  const { sites, selectedSite, selectSite } = useTenant();
  const [typeFilter, setTypeFilter] = useState<SiteReportType | "">("");
  const [statusFilter, setStatusFilter] = useState<SiteReportStatus | "">("");
  const [state, setState] = useState<
    { status: "loading" } | { status: "ready"; data: SiteReportListResponse } | { status: "error" }
  >({ status: "loading" });
  const [expanded, setExpanded] = useState<string | null>(null);
  const [notice, setNotice] = useState<string | null>(null);
  const siteId = selectedSite?.site_id ?? null;

  const load = useCallback(
    (signal?: AbortSignal) => {
      if (!siteId) return Promise.resolve();
      return getSiteReports(siteId, typeFilter || null, { signal })
        .then((data) => setState({ status: "ready", data }))
        .catch((error: unknown) => {
          if (error instanceof DOMException && error.name === "AbortError") return;
          setState({ status: "error" });
        });
    },
    [siteId, typeFilter],
  );

  useEffect(() => {
    const controller = new AbortController();
    setState({ status: "loading" });
    void load(controller.signal);
    return () => controller.abort();
  }, [load]);

  const active =
    state.status === "ready" && state.data.reports.some((r) => r.status === "PENDING" || r.status === "PROCESSING");
  useEffect(() => {
    if (!active) return;
    const timer = window.setInterval(() => void load(), POLL_MS);
    return () => window.clearInterval(timer);
  }, [active, load]);

  const reports = useMemo(
    () =>
      state.status === "ready" ? state.data.reports.filter((r) => !statusFilter || r.status === statusFilter) : [],
    [state, statusFilter],
  );

  if (!selectedSite) return null;
  const timeZone = state.status === "ready" ? state.data.timezone : selectedSite.timezone ?? "UTC";

  async function onDownload(report: SiteReportItem) {
    if (!report.download_version_id) return;
    setNotice(null);
    try {
      await saveVersion(report.download_version_id, "report.pdf");
    } catch {
      setNotice(CREATE_REPORT_MESSAGES.downloadFailed);
    }
  }

  return (
    <section className="page page--reports" data-testid="page-create-report" aria-label="Create report">
      <header className="reports-header">
        <h1 className="reports-header__title">Reports</h1>
        <p className="reports-header__subtitle">
          Weekly and monthly energy-performance reports (PDF). {CREATE_REPORT_MESSAGES.readOnly}
        </p>
      </header>

      <div className="reports-card">
        <div className="reports-controls">
          <label className="reports-field">
            <span className="reports-field__label">Site</span>
            <select value={selectedSite.site_id} onChange={(e) => selectSite(e.target.value)} data-testid="create-report-site">
              {sites.map((site) => (
                <option key={site.site_id} value={site.site_id}>
                  {site.site_name}
                </option>
              ))}
            </select>
          </label>
          <label className="reports-field">
            <span className="reports-field__label">Type</span>
            <select
              value={typeFilter}
              onChange={(e) => setTypeFilter(e.target.value as SiteReportType | "")}
              data-testid="create-report-type"
            >
              <option value="">All</option>
              <option value="WEEKLY">Weekly</option>
              <option value="MONTHLY">Monthly</option>
            </select>
          </label>
          <label className="reports-field">
            <span className="reports-field__label">Status</span>
            <select
              value={statusFilter}
              onChange={(e) => setStatusFilter(e.target.value as SiteReportStatus | "")}
              data-testid="create-report-status"
            >
              <option value="">All</option>
              {(Object.keys(STATUS_LABEL) as SiteReportStatus[]).map((s) => (
                <option key={s} value={s}>
                  {STATUS_LABEL[s]}
                </option>
              ))}
            </select>
          </label>
        </div>
        {state.status === "ready" && state.data.enrolled ? (
          <p className="reports-field__label" data-testid="create-report-schedule">
            Automatic weekly reports: {state.data.weekly_enabled ? "On" : "Paused"} · Automatic monthly reports:{" "}
            {state.data.monthly_enabled ? "On" : "Paused"} · All times {timeZone}
          </p>
        ) : null}
        {notice ? (
          <p className="reports-notice reports-notice--error" role="alert">
            {notice}
          </p>
        ) : null}

        {state.status === "loading" ? <p className="reports-field__label">Loading reports…</p> : null}
        {state.status === "error" ? (
          <p className="reports-notice reports-notice--error" role="alert">
            {CREATE_REPORT_MESSAGES.loadFailed}
          </p>
        ) : null}
        {state.status === "ready" && !state.data.enrolled ? <EmptyState title={CREATE_REPORT_MESSAGES.notEnrolled} /> : null}
        {state.status === "ready" && state.data.enrolled && reports.length === 0 ? (
          <EmptyState title={CREATE_REPORT_MESSAGES.empty} />
        ) : null}
        {state.status === "ready" && reports.length > 0 ? (
          <div className="reports-table-wrap">
            <table className="reports-table" data-testid="create-report-table">
              <thead>
                <tr>
                  <th>Type</th>
                  <th>Reporting period</th>
                  <th>Comparison period</th>
                  <th>Generated</th>
                  <th>Status</th>
                  <th>Data coverage</th>
                  <th>Version</th>
                  <th>Expires</th>
                  <th>Actions</th>
                </tr>
              </thead>
              <tbody>
                {reports.map((report) => (
                  <ReportRow
                    key={report.report_id}
                    report={report}
                    timeZone={timeZone}
                    expanded={expanded === report.report_id}
                    onToggle={() => setExpanded(expanded === report.report_id ? null : report.report_id)}
                    onDownload={() => void onDownload(report)}
                  />
                ))}
              </tbody>
            </table>
          </div>
        ) : null}
      </div>
    </section>
  );
}

function ReportRow(props: {
  report: SiteReportItem;
  timeZone: string;
  expanded: boolean;
  onToggle: () => void;
  onDownload: () => void;
}) {
  const { report, timeZone } = props;
  const coverage = report.coverage_summary;
  return (
    <>
      <tr data-testid="create-report-row">
        <td>{report.report_type === "WEEKLY" ? "Weekly" : "Monthly"}</td>
        <td>{periodText(report)}</td>
        <td>{periodText(report, true)}</td>
        <td>{formatInstant(report.generated_at, timeZone)}</td>
        <td>
          <span className={`reports-status reports-status--${STATUS_TONE[report.status]}`} data-testid="create-report-status-pill">
            {STATUS_LABEL[report.status]}
          </span>{" "}
          {report.incomplete_data ? (
            <span className="reports-status reports-status--bad" data-testid="label-incomplete">
              Incomplete data
            </span>
          ) : null}{" "}
          {report.comparison_incomplete ? (
            <span className="reports-status reports-status--neutral" data-testid="label-comparison-incomplete">
              Comparison incomplete
            </span>
          ) : null}
          {report.status_reason && (report.status === "PENDING" || report.status === "FAILED") ? (
            <div className="reports-field__label">{report.status_reason}</div>
          ) : null}
        </td>
        <td>
          {coverage ? `HVAC ${pct(coverage.hvac_available_pct)} · Kitchen ${pct(coverage.kitchen_available_pct)}` : "—"}
        </td>
        <td>{report.latest_version_no ? `v${report.latest_version_no}` : "—"}</td>
        <td>{report.download_version_id ? formatInstant(report.expires_at, timeZone) : report.latest_version_no ? "Expired" : "—"}</td>
        <td>
          <div className="reports-actions">
            {report.download_version_id ? (
              <button type="button" className="analytics-button" onClick={props.onDownload} data-testid="create-report-download">
                Download PDF
              </button>
            ) : null}
            {report.latest_version_no ? (
              <button type="button" className="analytics-button" onClick={props.onToggle} aria-expanded={props.expanded}>
                {props.expanded ? "Hide details" : "Version details"}
              </button>
            ) : null}
          </div>
        </td>
      </tr>
      {props.expanded ? (
        <tr>
          <td colSpan={9}>
            <VersionDetails reportId={report.report_id} timeZone={timeZone} />
          </td>
        </tr>
      ) : null}
    </>
  );
}

function coverageRows(coverage: Record<string, unknown>): Array<[string, string]> {
  const current = (coverage.current ?? {}) as Record<string, Record<string, unknown>>;
  const rows: Array<[string, string]> = [];
  for (const [label, key] of [
    ["HVAC", "hvac"],
    ["Kitchen", "kitchen"],
  ] as const) {
    const g = current[key];
    if (g) {
      rows.push([
        label,
        `${pct(g.available_pct)} available · ${pct(g.measured_pct)} measured · ${pct(g.reconstructed_pct)} EMS-reconstructed · ${pct(
          g.gap_filled_pct,
        )} gap-filled · ${pct(g.missing_pct)} missing`,
      ]);
    }
  }
  const peak = (coverage.current as Record<string, unknown> | undefined)?.peak_coverage_pct;
  if (typeof peak === "number") rows.push(["Peak demand coverage", pct(peak)]);
  const affected = coverage.affected_assets as string[] | undefined;
  if (affected && affected.length) rows.push(["Meters with missing or partial days", affected.join(", ")]);
  const notMonitored = coverage.not_temperature_monitored as string[] | undefined;
  if (notMonitored && notMonitored.length) rows.push(["Not temperature-monitored", notMonitored.join(", ")]);
  const reasons = coverage.comparison_reasons as string[] | undefined;
  if (reasons && reasons.length) rows.push(["Comparison period", `Incomplete: ${reasons.join("; ")}`]);
  return rows;
}

function settingRows(snapshot: Record<string, unknown>): string[] {
  const settings = (snapshot.settings ?? []) as Array<Record<string, unknown>>;
  return settings.map((s) => {
    const value = s.value as Record<string, unknown>;
    const text =
      s.setting === "TEMPERATURE_SETPOINT"
        ? `setpoint ${Number(value.value_c).toFixed(1)} °C`
        : s.setting === "OPERATING_SCHEDULE"
          ? `schedule ${String(s.description ?? "")}`
          : `thresholds OFF ${String(value.off_kw)} / ON ${String(value.on_kw)} kW`;
    return `${String(s.asset_name)}: ${text} (from ${String(s.effective_from).slice(0, 16).replace("T", " ")})`;
  });
}

function VersionDetails({ reportId, timeZone }: { reportId: string; timeZone: string }) {
  const [versions, setVersions] = useState<SiteReportVersion[] | null>(null);
  const [failed, setFailed] = useState(false);
  useEffect(() => {
    const controller = new AbortController();
    getSiteReportVersions(reportId, { signal: controller.signal })
      .then((r) => setVersions(r.versions))
      .catch(() => setFailed(true));
    return () => controller.abort();
  }, [reportId]);
  if (failed) return <p className="reports-notice reports-notice--error">{CREATE_REPORT_MESSAGES.loadFailed}</p>;
  if (!versions) return <p className="reports-field__label">Loading versions…</p>;
  return (
    <div data-testid="create-report-versions">
      {versions.map((v) => (
        <div key={v.version_id} className="reports-card" style={{ marginBottom: 8 }}>
          <p>
            <strong>v{v.version_no}</strong> · generated {formatInstant(v.generated_at, timeZone)} · expires{" "}
            {formatInstant(v.expires_at, timeZone)} · {v.page_count} pages{" "}
            {v.incomplete_data ? <span className="reports-status reports-status--bad">Incomplete data</span> : null}{" "}
            {v.comparison_incomplete ? (
              <span className="reports-status reports-status--neutral">Comparison incomplete</span>
            ) : null}{" "}
            {v.available ? (
              <button type="button" className="analytics-button" onClick={() => void saveVersion(v.version_id, v.file_name)}>
                Download v{v.version_no}
              </button>
            ) : (
              <span className="reports-field__label">Expired</span>
            )}
          </p>
          <table className="reports-table">
            <tbody>
              {coverageRows(v.coverage).map(([label, text]) => (
                <tr key={label}>
                  <th scope="row">{label}</th>
                  <td>{text}</td>
                </tr>
              ))}
            </tbody>
          </table>
          {settingRows(v.settings_snapshot).length ? (
            <details>
              <summary>Settings used</summary>
              <ul>
                {settingRows(v.settings_snapshot).map((line) => (
                  <li key={line}>{line}</li>
                ))}
              </ul>
            </details>
          ) : null}
        </div>
      ))}
    </div>
  );
}
